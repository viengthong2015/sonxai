#!/usr/bin/env node
/**
 * Collects every admin-panel text into src/admin/catalog.ts so it can be translated on the
 * Languages screen ("Admin panel text"). Run after changing admin wording:
 *
 *   npm run i18n:extract
 *
 * Sources:
 *  - frontend: at('…'), msg('…'), tr('…') calls (including both branches of at(x ? '…' : '…'))
 *  - backend:  fixed error messages, e.g. HTTPException(status, "…") and raise XError("…")
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, '..');
const backend = join(frontend, '..', 'backend', 'app');
const out = join(frontend, 'src', 'admin', 'catalog.ts');

function walk(dir, exts) {
  const files = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) files.push(...walk(p, exts));
    else if (exts.includes(extname(p))) files.push(p);
  }
  return files;
}

const unescape = (s) => s.replace(/\\(['"\\])/g, '$1').replace(/\\n/g, '\n');
const strings = new Map(); // text -> first file

function add(text, file) {
  const t = unescape(text).trim();
  if (t && /[A-Za-z]/.test(t) && !strings.has(t)) strings.set(t, relative(frontend, file));
}

const STR = String.raw`(['"])((?:\\.|(?!\1)[^\\\n])*)\1`;
const callRe = new RegExp(String.raw`\b(?:at|msg|tr)\(\s*` + STR, 'g');
const ternaryRe = new RegExp(String.raw`\bat\([^'"\n()]*\?\s*` + STR + String.raw`\s*:\s*(['"])((?:\\.|(?!\3)[^\\\n])*)\3`, 'g');

const frontendFiles = [
  ...walk(join(frontend, 'src', 'admin'), ['.ts', '.tsx']).filter((f) => !f.endsWith('catalog.ts')),
  join(frontend, 'src', 'lib', 'api.ts'),
  join(frontend, 'src', 'lib', 'colors.ts'),
  join(frontend, 'src', 'public', 'PublicLayout.tsx'),
];
for (const file of frontendFiles) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(ternaryRe)) {
    add(m[2], file);
    add(m[4], file);
  }
  for (const m of src.matchAll(callRe)) add(m[2], file);
}

// Backend: constant (non f-string) messages shown to staff.
const pyRe = [
  /HTTPException\(\s*[\w.]+\s*,\s*"((?:\\.|[^"\\])*)"/g,
  /raise \w+(?:Error|Exception)\(\s*"((?:\\.|[^"\\])*)"/g,
  /raise ValueError\(\s*"((?:\\.|[^"\\])*)"/g,
  /\{"detail": "((?:\\.|[^"\\])*)"\}/g,
];
for (const file of walk(backend, ['.py'])) {
  const src = readFileSync(file, 'utf8');
  for (const re of pyRe) for (const m of src.matchAll(re)) add(m[1], file);
}

const body = [...strings.keys()].map((s) => `  ${JSON.stringify(s)},`).join('\n');
writeFileSync(
  out,
  `/* Generated by scripts/extract-admin-strings.mjs. Do not edit by hand: run \`npm run i18n:extract\`. */\nexport const ADMIN_CATALOG: string[] = [\n${body}\n];\n`,
);
console.log(`Wrote ${strings.size} admin texts to ${relative(frontend, out)}`);
